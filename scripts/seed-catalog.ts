// Writes supabase/seed.sql from the exercise catalog, so the plan-engine tests and the database
// share one source. Runs on Node 24 (.nvmrc): `npm run db:seed`.

import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CATALOG } from '../supabase/functions/_shared/rules/catalog.ts';
import type { Exercise } from '../supabase/functions/_shared/rules/types.ts';

export const SEED_PATH = fileURLToPath(new URL('../supabase/seed.sql', import.meta.url));

const COLUMNS = [
  'slug',
  'name',
  'movement_pattern',
  'equipment',
  'muscle_great',
  'muscle_light',
  'regions_great',
  'regions_light',
  'increment_lb',
  'min_load_lb',
  'is_main_lift',
  'allowed_swaps',
  'cues',
] as const;

const text = (value: string): string => `'${value.replaceAll("'", "''")}'`;

const textArray = (values: readonly string[]): string =>
  `array[${values.map(text).join(', ')}]::text[]`;

function exerciseRow(e: Exercise): string {
  return [
    '  (',
    `    ${text(e.slug)}, ${text(e.name)}, ${text(e.movementPattern)}, ${textArray(e.equipment)},`,
    `    ${text(e.muscleGreat)}, ${e.muscleLight === null ? 'null' : text(e.muscleLight)},`,
    `    ${textArray(e.regionsGreat)}, ${textArray(e.regionsLight)},`,
    `    ${e.incrementLb}, ${e.minLoadLb}, ${e.isMainLift},`,
    `    ${textArray(e.allowedSwaps)},`,
    `    ${textArray(e.cues)}`,
    '  )',
  ].join('\n');
}

export function catalogSeedSql(catalog: readonly Exercise[]): string {
  const updates = COLUMNS.filter((column) => column !== 'slug').map(
    (column) => `  ${column} = excluded.${column}`,
  );
  return [
    '-- Generated by `npm run db:seed` from supabase/functions/_shared/rules/catalog.ts. Do not edit by hand.',
    `insert into public.exercises (${COLUMNS.join(', ')})`,
    'values',
    catalog.map(exerciseRow).join(',\n'),
    'on conflict (slug) do update set',
    `${updates.join(',\n')};`,
    '',
  ].join('\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(SEED_PATH, catalogSeedSql(CATALOG));
}
